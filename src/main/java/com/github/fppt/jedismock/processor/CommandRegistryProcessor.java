package com.github.fppt.jedismock.processor;

import com.palantir.javapoet.ClassName;
import com.palantir.javapoet.CodeBlock;
import com.palantir.javapoet.FieldSpec;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.MethodSpec;
import com.palantir.javapoet.ParameterizedTypeName;
import com.palantir.javapoet.TypeName;
import com.palantir.javapoet.TypeSpec;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.AnnotationMirror;
import javax.lang.model.element.AnnotationValue;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.VariableElement;
import javax.lang.model.type.TypeMirror;
import javax.lang.model.util.ElementFilter;
import javax.tools.Diagnostic;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.SortedMap;
import java.util.TreeMap;

/**
 * Generates, at compile time, the command table that {@code CommandFactory} looks
 * commands up in.
 *
 * <p>Every class carrying {@code @RedisCommand} is reported to this processor by
 * javac, so the commands are located by the compiler rather than by scanning the
 * classpath at start-up. For each command the processor emits a
 * {@code CommandDescriptor}: the annotation's members ({@code transactional},
 * {@code arity}, {@code readOnly}) as literals, plus a lambda that calls the
 * operation's constructor with its arguments resolved from their declared types.
 * A constructor parameter of a type that cannot be supplied is a compile error
 * at the parameter.
 *
 * <p>Most operation classes are package-private, so the lambdas cannot live in a
 * single class: the processor writes one {@code Commands} registrar per command
 * package, next to the operations it constructs, and a {@code CommandRegistries}
 * class in {@code com.github.fppt.jedismock.operations} that assembles them into
 * one map. Nothing is loaded by name, so the artifact survives a minifier.
 *
 * <p>The table covers whatever javac was handed, which is not always the whole
 * source tree. Compile a subset and the table is regenerated for that subset alone:
 * recompiling one command on its own yields a table holding that one command.
 * Maven recompiles every source once any of them is stale, so a Maven build always
 * sees them all; an IDE compiling incrementally may not. Rebuild before trusting a
 * table that looks short.
 *
 * <p>This class is a build-time tool. javac cannot run a processor it is
 * compiling, so the build compiles this package first, on its own, into
 * {@code target/processor-classes} and passes that to the main compilation on
 * the processor path. The main compilation excludes this package, so neither it
 * nor JavaPoet ends up in the published artifact.
 */
@SupportedAnnotationTypes(CommandRegistryProcessor.REDIS_COMMAND)
public final class CommandRegistryProcessor extends AbstractProcessor {

    static final String REDIS_COMMAND = "com.github.fppt.jedismock.operations.RedisCommand";

    private static final String OPERATIONS_PACKAGE = "com.github.fppt.jedismock.operations";
    private static final String REDIS_OPERATION = OPERATIONS_PACKAGE + ".RedisOperation";
    private static final String DESCRIPTOR = OPERATIONS_PACKAGE + ".CommandDescriptor";
    private static final String REGISTRIES_CLASS = "CommandRegistries";
    private static final String REGISTRAR_CLASS = "Commands";
    private static final String COMMANDS_FIELD = "commands";
    private static final String REGISTER_METHOD = "register";
    private static final String GENERATED_BY =
            "Generated by " + CommandRegistryProcessor.class.getName() + ". Do not edit.\n";

    /**
     * The expression that supplies a constructor parameter of each injectable type,
     * by the erased type name. The lambda's parameters are {@code state} and
     * {@code params}.
     */
    private static final Map<String, String> INJECTIONS;

    static {
        Map<String, String> injections = new HashMap<>();
        injections.put("java.util.List", "params");
        injections.put("com.github.fppt.jedismock.storage.OperationExecutorState", "state");
        injections.put("com.github.fppt.jedismock.storage.RedisBase", "state.base()");
        injections.put("com.github.fppt.jedismock.storage.SubscriptionRegistry", "state.subscriptionRegistry()");
        injections.put("com.github.fppt.jedismock.RedisClient", "state.owner()");
        INJECTIONS = Collections.unmodifiableMap(injections);
    }

    /**
     * Commands by the package of their class, then by command name. Both orders are
     * kept stable so that a rebuild produces byte-identical sources.
     */
    private final SortedMap<String, SortedMap<String, Command>> commandsByPackage = new TreeMap<>();

    /** Every command by name, to reject two classes claiming the same name. */
    private final Map<String, Command> commandsByName = new HashMap<>();

    private boolean written;

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
        if (roundEnv.processingOver()) {
            return false;
        }
        TypeElement redisCommand = processingEnv.getElementUtils().getTypeElement(REDIS_COMMAND);
        if (redisCommand == null) {
            return false;
        }
        for (Element element : roundEnv.getElementsAnnotatedWith(redisCommand)) {
            collect(element);
        }
        //Every operation is an original source file, so they have all been seen by the end of
        //the first round that reported any. Writing here rather than in the final round keeps
        //the generated sources subject to annotation processing themselves.
        if (!written && !commandsByPackage.isEmpty() && !annotations.isEmpty()) {
            written = true;
            write();
        }
        return false;
    }

    private void collect(Element element) {
        if (element.getKind() != ElementKind.CLASS) {
            error(element, "@RedisCommand may only annotate classes");
            return;
        }
        TypeElement type = (TypeElement) element;
        if (type.getModifiers().contains(Modifier.ABSTRACT)) {
            error(type, "@RedisCommand class must not be abstract");
            return;
        }
        if (type.getNestingKind().isNested() && !type.getModifiers().contains(Modifier.STATIC)) {
            error(type, "@RedisCommand class must be top level or a static nested class");
            return;
        }
        if (!isRedisOperation(type)) {
            error(type, "@RedisCommand class must implement " + REDIS_OPERATION);
            return;
        }
        String packageName = processingEnv.getElementUtils()
                .getPackageOf(type).getQualifiedName().toString();
        if (!packageName.equals(OPERATIONS_PACKAGE) && !packageName.startsWith(OPERATIONS_PACKAGE + ".")) {
            error(type, "@RedisCommand class must live in " + OPERATIONS_PACKAGE + " or a subpackage of it");
            return;
        }
        Map<String, AnnotationValue> values = redisCommandValues(type);
        if (values == null) {
            return;
        }
        List<String> arguments = constructorArguments(type);
        if (arguments == null) {
            return;
        }
        String name = (String) values.get("value").getValue();
        Command command = new Command(name,
                (Boolean) values.get("transactional").getValue(),
                (Integer) values.get("arity").getValue(),
                (Boolean) values.get("readOnly").getValue(),
                type, arguments);

        Command clash = commandsByName.put(name, command);
        if (clash != null) {
            //Generated puts would silently drop one of the two, so reject the clash here instead.
            error(type, "@RedisCommand(\"" + name + "\") is already declared by "
                    + clash.declaration.getQualifiedName());
            error(clash.declaration, "@RedisCommand(\"" + name + "\") is also declared by "
                    + type.getQualifiedName());
            return;
        }
        commandsByPackage.computeIfAbsent(packageName, p -> new TreeMap<>()).put(name, command);
    }

    /**
     * The {@code @RedisCommand} members of a command class, defaults filled in, by
     * member name. The annotation is read through mirrors rather than reflectively
     * because this processor is compiled on its own, without the library on its
     * classpath.
     */
    private Map<String, AnnotationValue> redisCommandValues(TypeElement type) {
        for (AnnotationMirror mirror : type.getAnnotationMirrors()) {
            TypeElement annotation = (TypeElement) mirror.getAnnotationType().asElement();
            if (!annotation.getQualifiedName().contentEquals(REDIS_COMMAND)) {
                continue;
            }
            Map<String, AnnotationValue> values = new HashMap<>();
            for (Map.Entry<? extends ExecutableElement, ? extends AnnotationValue> member
                    : processingEnv.getElementUtils().getElementValuesWithDefaults(mirror).entrySet()) {
                values.put(member.getKey().getSimpleName().toString(), member.getValue());
            }
            return values;
        }
        error(type, "@RedisCommand is not present on " + type.getQualifiedName());
        return null;
    }

    /**
     * The expressions supplying the arguments of the command's constructor, in
     * order, or {@code null} after reporting why it cannot be called.
     */
    private List<String> constructorArguments(TypeElement type) {
        List<ExecutableElement> constructors = ElementFilter.constructorsIn(type.getEnclosedElements());
        if (constructors.size() != 1) {
            error(type, "@RedisCommand class must declare exactly one constructor");
            return null;
        }
        ExecutableElement constructor = constructors.get(0);
        if (constructor.getModifiers().contains(Modifier.PRIVATE)) {
            error(constructor, "@RedisCommand class constructor must not be private: "
                    + "the generated registrar in its package calls it");
            return null;
        }
        List<String> arguments = new ArrayList<>();
        for (VariableElement parameter : constructor.getParameters()) {
            String erased = processingEnv.getTypeUtils().erasure(parameter.asType()).toString();
            String supplied = INJECTIONS.get(erased);
            if (supplied == null) {
                error(parameter, "Cannot supply a constructor parameter of type " + erased
                        + "; a command constructor may only take " + new TreeMap<>(INJECTIONS).keySet());
                return null;
            }
            arguments.add(supplied);
        }
        return arguments;
    }

    private boolean isRedisOperation(TypeElement type) {
        TypeElement operation = processingEnv.getElementUtils().getTypeElement(REDIS_OPERATION);
        if (operation == null) {
            //RedisOperation is compiled alongside the commands, so this only happens if the
            //annotation is used from outside the library, where we cannot check the bound.
            return true;
        }
        TypeMirror erasedOperation = processingEnv.getTypeUtils().erasure(operation.asType());
        TypeMirror erasedType = processingEnv.getTypeUtils().erasure(type.asType());
        return processingEnv.getTypeUtils().isAssignable(erasedType, erasedOperation);
    }

    private void write() {
        ClassName descriptor = ClassName.bestGuess(DESCRIPTOR);
        TypeName table = ParameterizedTypeName.get(ClassName.get(Map.class),
                ClassName.get(String.class), descriptor);
        for (Map.Entry<String, SortedMap<String, Command>> entry : commandsByPackage.entrySet()) {
            writeRegistrar(entry.getKey(), entry.getValue(), descriptor, table);
        }
        writeRegistries(table);
    }

    /**
     * One {@code Commands} class per command package, holding a descriptor for each
     * command declared there. It sits in the package so that the lambda can call
     * the package-private constructor.
     */
    private void writeRegistrar(String packageName, SortedMap<String, Command> commands,
                                ClassName descriptor, TypeName table) {
        MethodSpec.Builder register = MethodSpec.methodBuilder(REGISTER_METHOD)
                .addJavadoc("Adds the commands of this package to the table, by name.\n")
                .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
                .addParameter(table, "table");
        TypeSpec.Builder spec = TypeSpec.classBuilder(REGISTRAR_CLASS)
                .addJavadoc("The commands declared in this package, built from their {@code $L} "
                        + "annotations.\n\n<p>Internal API.\n", REDIS_COMMAND)
                .addJavadoc("\n<p>$L", GENERATED_BY)
                .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
                .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());
        for (Command command : commands.values()) {
            spec.addOriginatingElement(command.declaration);
            register.addStatement("table.put($S, new $T($S, $L, $L, $L, (state, params) -> new $T($L)))",
                    command.name, descriptor, command.name, command.transactional, command.arity,
                    command.readOnly, ClassName.get(command.declaration), String.join(", ", command.arguments));
        }
        writeTo(packageName, spec.addMethod(register.build()).build());
    }

    /** The single table of every command, assembled from the registrars. */
    private void writeRegistries(TypeName table) {
        CodeBlock.Builder assembly = CodeBlock.builder()
                .addStatement("$T table = new $T<>()", table, HashMap.class);
        for (String packageName : commandsByPackage.keySet()) {
            assembly.addStatement("$L.$L.$L(table)", packageName, REGISTRAR_CLASS, REGISTER_METHOD);
        }
        assembly.addStatement("$L = $T.unmodifiableMap(table)", COMMANDS_FIELD, Collections.class);

        TypeSpec spec = TypeSpec.classBuilder(REGISTRIES_CLASS)
                .addJavadoc("Every command in the library, by name.\n\n"
                        + "<p>Internal API, the table {@link CommandFactory} looks commands up in. It is "
                        + "written at compile time from the annotations of the classes javac was handed, "
                        + "so an incremental build that recompiles only some of them leaves a table for "
                        + "only those. Rebuild before trusting a table that looks short.\n")
                .addJavadoc("\n<p>$L", GENERATED_BY)
                .addModifiers(Modifier.FINAL, Modifier.PUBLIC)
                .addField(FieldSpec.builder(table, COMMANDS_FIELD,
                        Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL).build())
                .addStaticBlock(assembly.build())
                .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build())
                .build();
        writeTo(OPERATIONS_PACKAGE, spec);
    }

    private void writeTo(String packageName, TypeSpec spec) {
        try {
            JavaFile.builder(packageName, spec)
                    .skipJavaLangImports(true)
                    .indent("    ")
                    .build()
                    .writeTo(processingEnv.getFiler());
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot write " + packageName + "." + spec.name(), e);
        }
    }

    private void error(Element element, String message) {
        processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, message, element);
    }

    /**
     * A command class with what its descriptor is built from, kept with the element
     * that declared it so that a duplicate command name can be reported against its
     * source.
     */
    private static final class Command {
        private final String name;
        private final boolean transactional;
        private final int arity;
        private final boolean readOnly;
        private final TypeElement declaration;
        private final List<String> arguments;

        Command(String name, boolean transactional, int arity, boolean readOnly,
                TypeElement declaration, List<String> arguments) {
            this.name = name;
            this.transactional = transactional;
            this.arity = arity;
            this.readOnly = readOnly;
            this.declaration = declaration;
            this.arguments = arguments;
        }
    }
}
